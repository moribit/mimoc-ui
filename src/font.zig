        '.' => .{ 0, 0x40, 0x40, 0, 0 },
        '/' => .{ 0x60, 0x10, 0x08, 0x04, 0x03 },
        '%' => .{ 0x63, 0x13, 0x08, 0x64, 0x63 },
        '>' => .{ 0x41, 0x22, 0x14, 0x08, 0 },
        '<' => .{ 0, 0x08, 0x14, 0x22, 0x41 },
        '[' => .{ 0, 0x7f, 0x41, 0x41, 0 },
        ']' => .{ 0, 0x41, 0x41, 0x7f, 0 },
        '?' => .{ 0x02, 0x01, 0x51, 0x09, 0x06 },
        else => glyph('?'),
    };
}
